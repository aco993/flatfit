export const DICT: Record<Lang, Record<Key, string>> = { en, de, sr, bs, hr };
export const LANGS: { id: Lang; label: string; locale: string }[] = [
  { id: 'en', label: 'English', locale: 'en-GB' },
  { id: 'de', label: 'Deutsch', locale: 'de-DE' },
  { id: 'sr', label: 'Srpski', locale: 'sr-Latn-RS' },
  // Chrome ships without Bosnian number/date data (it prints 'BAM 8,087.85'); Serbian Latin for Bosnia formats
  // amounts and month names the way Bosnian does ('8.087,85 KM', 'novembar'). The page language stays 'bs'.
  { id: 'bs', label: 'Bosanski', locale: 'sr-Latn-BA' },
  { id: 'hr', label: 'Hrvatski', locale: 'hr-HR' },
];

let current: Lang = 'en';
export const setLang = (l: Lang) => {
  current = l;
};
export const getLang = () => current;
export function t(k: Key, v: Record<string, string | number> = {}): string {
  const s = DICT[current][k] ?? en[k] ?? k;
  return s.replace(/\{(\w+)\}/g, (_, n) => (v[n] !== undefined ? String(v[n]) : ''));
}
export const tt = (k: string, v?: Record<string, string | number>) => t(k as Key, v);
export function detectLang(): Lang {
  const l = (navigator.languages || [navigator.language]).map(x => x.toLowerCase());
  for (const x of l) {
    if (x.startsWith('de')) return 'de';
    if (x.startsWith('bs')) return 'bs';
    if (x.startsWith('hr')) return 'hr';
    if (/^(sr|sh|me|cnr)/.test(x)) return 'sr';
    if (x.startsWith('en')) return 'en';
  }
  return 'en';
}
