/** English is built in (it is also the fallback for a missing word); the other languages load when chosen. */
const LOADERS: Record<Exclude<Lang, 'en'>, () => Promise<{ default: Record<Key, string> }>> = {
  de: () => import('./i18n/de'),
  sr: () => import('./i18n/sr'),
  bs: () => import('./i18n/bs'),
  hr: () => import('./i18n/hr'),
};
const loaded: Partial<Record<Lang, Record<Key, string>>> = { en };
export { en as EN };
/** Load a language's words (once); t() falls back to English until they are here. */
export async function loadLang(l: Lang) {
  if (!loaded[l] && l !== 'en') loaded[l] = (await LOADERS[l]()).default;
}
/** Load a language and switch to it. */
export async function useLang(l: Lang) {
  await loadLang(l);
  setLang(l);
}
export const isLang = (l: string): l is Lang => LANGS.some(x => x.id === l);
export const LANGS: { id: Lang; label: string; locale: string }[] = [
  { id: 'en', label: 'English', locale: 'en-GB' },
  { id: 'de', label: 'Deutsch', locale: 'de-DE' },
  { id: 'sr', label: 'Srpski', locale: 'sr-Latn-RS' },
  // Chrome ships without Bosnian number/date data (it prints 'BAM 8,087.85'); Serbian Latin for Bosnia formats
  // amounts and month names the way Bosnian does ('8.087,85 KM', 'novembar'). The page language stays 'bs'.
  { id: 'bs', label: 'Bosanski', locale: 'sr-Latn-BA' },
  { id: 'hr', label: 'Hrvatski', locale: 'hr-HR' },
];

let current: Lang = 'en';
export const setLang = (l: Lang) => {
  current = l;
};
export const getLang = () => current;
/**
 * Fills {name} placeholders. {n:one|other} (two forms) or {n:one|few|other} (Slavic languages) picks the word form
 * for the number in n by the language's plural rules: "1 item", "2 stavke", "5 stavki".
 */
export function t(k: Key, v: Record<string, string | number> = {}): string {
  const s = loaded[current]?.[k] ?? en[k] ?? k;
  return s
    .replace(/\{(\w+):([^}]*)\}/g, (_, n, forms: string) => pluralForm(Number(v[n]), forms.split('|')))
    .replace(/\{(\w+)\}/g, (_, n) => (v[n] !== undefined ? String(v[n]) : ''));
}
const rules = new Map<string, Intl.PluralRules>();
function pluralForm(n: number, forms: string[]) {
  const locale = LANGS.find(l => l.id === current)?.locale || 'en';
  let r = rules.get(locale);
  if (!r) {
    r = new Intl.PluralRules(locale);
    rules.set(locale, r);
  }
  const cat = r.select(Number.isFinite(n) ? n : 0);
  if (forms.length >= 3) return cat === 'one' ? forms[0] : cat === 'few' ? forms[1] : forms[2];
  return cat === 'one' ? forms[0] : forms[forms.length - 1];
}
export const tt = (k: string, v?: Record<string, string | number>) => t(k as Key, v);
export function detectLang(): Lang {
  const l = (navigator.languages || [navigator.language]).map(x => x.toLowerCase());
  for (const x of l) {
    if (x.startsWith('de')) return 'de';
    if (x.startsWith('bs')) return 'bs';
    if (x.startsWith('hr')) return 'hr';
    if (/^(sr|sh|me|cnr)/.test(x)) return 'sr';
    if (x.startsWith('en')) return 'en';
  }
  return 'en';
}
